import { Bot, webhookCallback } from 'grammy'
import { BOT_TOKEN } from './auth'
import { APP_URL } from './env'

export const bot = BOT_TOKEN ? new Bot(BOT_TOKEN) : null

const OPEN = 'Играть ⚫️⚪️'

export function appKeyboard(startParam?: string) {
  if (!APP_URL) return undefined
  const url = startParam ? `${APP_URL}?startapp=${encodeURIComponent(startParam)}` : APP_URL
  return { inline_keyboard: [[{ text: OPEN, web_app: { url } }]] }
}

if (bot) {
  void bot.api.setMyDescription(
    '«Камушки» это древняя игра го про окружение: ставь камни на пересечения, окружай пустые ' +
      'пункты и забирай их под свою территорию.\n\n' +
      'Камни не двигаются, но у каждой группы есть «дыхания», соседние пустые пункты. ' +
      'Окружишь чужую группу со всех сторон, и она снимается с доски как пленные. В конце ' +
      'считаем территорию плюс камни: у кого больше, тот и победил.\n\n' +
      'Правила учатся за минуту, а глубина бесконечная. Можно играть с ботами на трёх ' +
      'уровнях, найти случайного соперника онлайн или позвать друга в комнату по коду. ' +
      'Заходи на партейку!',
  ).catch(() => {})
  void bot.api.setMyShortDescription('«Камушки»: ставь камни, окружай территорию, забирай группы соперника. С ботами или друзьями ⚫️⚪️').catch(() => {})

  // Register the standard command menu (the list that pops up on "/").
  void bot.api.setMyCommands([
    { command: 'start', description: 'Открыть игру' },
    { command: 'play', description: 'Сыграть партию' },
    { command: 'rules', description: 'Как играть' },
    { command: 'about', description: 'Об игре' },
    { command: 'help', description: 'Помощь' },
  ]).catch(() => {})

  bot.command('start', async ctx => {
    const payload = ctx.match?.toString() ?? ''
    // a room deep-link: /start room_ABCD opens straight into that room
    const startParam = payload.startsWith('room_') ? payload : undefined
    const name = ctx.from?.first_name || 'друг'
    await ctx.reply(
      `Привет, ${name}! Это «Камушки» ⚫️⚪️\n\n` +
        'Если совсем просто, это древняя игра го про окружение на доске 9 на 9. Камни ставят ' +
        'на пересечения линий и больше не двигают. У тебя свой цвет, у соперника свой.\n\n' +
        'У каждой группы камней есть свободные соседние пункты, это её дыхания. Окружишь ' +
        'чужую группу так, что дыханий не осталось, и она снимается с доски. А ещё камнями ' +
        'обводят пустое место: оно становится твоей территорией.\n\n' +
        'В конце считаем территорию вместе с камнями. У кого больше, тот и выиграл, а белым ' +
        'добавляют коми за второй ход. Правила схватываешь за минуту, но играть можно всю жизнь.\n\n' +
        'Можно сыграть с ботами на трёх уровнях, найти соперника онлайн или позвать друга в ' +
        'комнату по коду. Жми кнопку «Играть» внизу и присаживайся к доске. Жду тебя! ⚫️⚪️',
      { reply_markup: appKeyboard(startParam) },
    )
  })

  bot.command('play', async ctx => {
    await ctx.reply('Расставляю доску ⚫️⚪️ Заходи на партейку!', { reply_markup: appKeyboard() })
  })

  bot.command('rules', async ctx => {
    await ctx.reply(
      'Правила Го ⚫️⚪️\n\n' +
        'Цель: к концу партии окружить больше пунктов, чем соперник.\n\n' +
        '• Доска 9 на 9, камни ставят на пересечения линий и не двигают.\n' +
        '• Чёрные ходят первыми, затем по очереди. Можно пропустить ход (пас).\n' +
        '• У группы соединённых камней есть дыхания, это соседние пустые пункты.\n' +
        '• Окружишь чужую группу так, что дыханий не осталось, и она снимается с доски ' +
        'как пленные.\n' +
        '• Нельзя ставить камень в самоубийство (без дыханий), если только этим ходом ты ' +
        'не снимаешь соперника.\n' +
        '• Правило ко: нельзя сразу отыграть назад и вернуть доску в прежнее положение.\n\n' +
        'Партия заканчивается, когда оба спасовали подряд. Считаем по площади: камни на ' +
        'доске плюс окружённая ими пустота. Белым добавляют коми. Доигрывайте границы до ' +
        'конца, чтобы счёт был честным.',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('about', async ctx => {
    await ctx.reply(
      '«Камушки» ⚫️⚪️\n\n' +
        'Древняя игра го про окружение, своя и без заимствований: спокойная партия, где из ' +
        'простых правил вырастает целая стратегия.\n\n' +
        'Как можно играть:\n' +
        '• Одиночная игра против бота, три уровня сложности.\n' +
        '• Быстрая игра, случайный соперник онлайн.\n' +
        '• С другом, общая комната по коду из четырёх символов.\n\n' +
        'Правила учатся за минуту, а до мастерства идти можно долго. ' +
        'Заходи на пару партий за вечер 💛',
      { reply_markup: appKeyboard() },
    )
  })

  bot.command('help', async ctx => {
    await ctx.reply(
      '«Камушки» ⚫️⚪️, древняя игра го про камни и территорию.\n\n' +
        'Команды:\n' +
        '/start - открыть игру\n' +
        '/play - сыграть партию\n' +
        '/rules - как играть\n' +
        '/about - об игре\n' +
        '/help - это сообщение\n\n' +
        'Жми кнопку ниже, чтобы играть 👇',
      { reply_markup: appKeyboard() },
    )
  })
}

export const botWebhook = bot ? webhookCallback(bot, 'hono') : null
